# A URL fica em Streamlit > Settings > Secrets, nunca no código.
DATABASE_URL = st.secrets["database"]["url"]

if DATABASE_URL.startswith("postgresql://"):
    DATABASE_URL = DATABASE_URL.replace(
        "postgresql://", "postgresql+psycopg2://", 1
    )

engine = create_engine(DATABASE_URL, pool_pre_ping=True)


class DatabaseAdapter:
    """Adapta chamadas simples do código antigo para SQLAlchemy/PostgreSQL."""
    def __init__(self, db_engine):
        self.engine = db_engine

    def cursor(self):
        return self

    def execute(self, sql, params=()):
        # Converte os marcadores ? antigos em parâmetros SQLAlchemy nomeados.
        if params:
            parts = sql.split("?")
            if len(parts) - 1 != len(params):
                raise ValueError("Quantidade de parâmetros SQL incompatível.")
            sql_parts = [parts[0]]
            values = {}
            for i, value in enumerate(params):
                key = f"p{i}"
                sql_parts.append(f":{key}")
                sql_parts.append(parts[i + 1])
                values[key] = value
            sql = "".join(sql_parts)
        else:
            values = {}
        with self.engine.begin() as db_conn:
            return db_conn.execute(text(sql), values)

    def commit(self):
        # Cada execute é confirmado dentro de engine.begin().
        return None

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        return False


conn = DatabaseAdapter(engine)
cur = conn.cursor()


with engine.begin() as db_conn:
    db_conn.execute(text("""
        CREATE TABLE IF NOT EXISTS f (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            data TEXT, item TEXT, valor DOUBLE PRECISION,
            tipo TEXT, classe TEXT
        )
    """))

    db_conn.execute(text("""
        CREATE TABLE IF NOT EXISTS fatura (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            data TEXT, item TEXT, valor DOUBLE PRECISION,
            parcelas INTEGER, cartao TEXT
        )
    """))

    db_conn.execute(text("""
        ALTER TABLE fatura
        ADD COLUMN IF NOT EXISTS primeira_parcela TEXT
    """))

    db_conn.execute(text("""
        CREATE TABLE IF NOT EXISTS metas (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nome TEXT, valor DOUBLE PRECISION, prazo INTEGER
        )
    """))



def get_df(t):
    # Só permite nomes de tabela definidos pelo próprio sistema.
    if t not in {"f", "fatura", "metas"}:
        return pd.DataFrame()
    try:
        return pd.read_sql(text(f"SELECT * FROM {t} ORDER BY id DESC"), engine)
    except Exception as e:
        st.error(f"Erro ao consultar o banco de dados: {e}")
        return pd.DataFrame()

   


